// Case-insensitive prefix-then-substring search over names and aliases.
export function searchIndiaPlaces(query, limit = 8){
  const q = query.trim().toLowerCase();
  if(!q) return [];
  const scored = [];
  for(const row of INDIA_PLACES){
    const names = [row[0], ...(row[4] || [])];
    let best = Infinity;
    for(const n of names){
      const l = n.toLowerCase();
      if(l === q) best = Math.min(best, 0);
      else if(l.startsWith(q)) best = Math.min(best, 1);
      else if(l.includes(q)) best = Math.min(best, 2);
    }
    if(best < Infinity) scored.push([best, row]);
  }
  scored.sort((a,b)=>a[0]-b[0] || a[1][0].localeCompare(b[1][0]));
  return scored.slice(0, limit).map(([,row])=>placeFromRow(row));
}

export function placeFromRow(row){
  return { name: row[0], lat: row[1], lon: row[2], region: INDIA_STATE_NAMES[row[3]] || '' };
}

// Nearest listed place to a coordinate (for naming a pin dropped by tapping
// the map), with its great-circle distance in km.
export function nearestIndiaPlace(lat, lon){
  let best = null;
  for(const row of INDIA_PLACES){
    const d = haversineKm(lat, lon, row[1], row[2]);
    if(!best || d < best.km) best = { place: placeFromRow(row), km: d };
  }
  return best;
}

function haversineKm(la1, lo1, la2, lo2){
  const R = 6371, rad = Math.PI/180;
  const dLa = (la2-la1)*rad, dLo = (lo2-lo1)*rad;
  const a = Math.sin(dLa/2)**2 + Math.cos(la1*rad)*Math.cos(la2*rad)*Math.sin(dLo/2)**2;
  return 2*R*Math.asin(Math.sqrt(a));
}
